def render(manifests_dir: Path = paths.MANIFESTS, pools_dir: Path = paths.POOLS, decontam: Path = paths.DECONTAM / "report.json") -> str:
    mx = read(manifests_dir / "mixture.json")
    sel = read(manifests_dir / "selection.json")
    sp = read(manifests_dir / "split.json")
    p1, p2 = read(manifests_dir / "screens_p1_pools.json"), read(manifests_dir / "screens_p2_rows.json")
    raw, excl = read(manifests_dir / "raw_sources.json"), read(manifests_dir / "decontam_exclusions.json")
    pools = {n: read(pools_dir / n / "manifest.json") for n in ("swe_teacher", "terminal_teacher", "retention")}
    adm = read(pools_dir / "terminal_teacher" / "admission_report.json")
    status = "missing" if not mx else ("FROZEN" if mx.get("frozen") else "CANDIDATE (not frozen)")
    lines = ["# Data card: the stage-1 SFT set", "",
             "> Generated by `scripts/data/write_data_card.py` from the manifests under `data/manifests/` and `data/pools/`; do not edit "
             "by hand. Plan: `docs/DATA_PLAN.md` (revision 4.3.x), changes in `docs/DATA_PLAN_CHANGELOG.md`.", "",
             f"**Status: {status}.** Mixture run `{(mx or {}).get('run_id')}`, written {(mx or {}).get('created')}; "
             f"frozen {((mx or {}).get('freeze') or {}).get('frozen_at', '–')}.", ""]
    if not mx:
        return "\n".join(lines + ["_data/manifests/mixture.json is missing: run scripts/data/build_mixture.py build_", ""])
    lines += section_summary(mx) + section_sources(mx, raw) + section_mixture(mx) + section_provenance(mx) + section_funnels(pools)
    lines += section_swe(mx, pools) + section_terminal(mx) + section_admission(adm) + section_screens(p1, p2, sel, pools)
    lines += section_split(sp) + section_exclusions(excl)
    lines += ["## 12. Limitations", "", *(f"- {x}" for x in LIMITATIONS), "",
              "## 13. Reproduction", "", "From the repository root, with `PYTHONPATH=src .venv/train/bin/python`:", "",
              "```", "scripts/data/build_mixture.py items            # p1 screen items from the pools (+ dev items)",
              "scripts/data/run_screens.py --pass-name p1_pools --pools '' --pool <name>=<items file> ...",
              "scripts/data/build_mixture.py build --cap 64k   # selection, budget rule, split, pilot, files, manifests",
              "scripts/data/run_screens.py --pass-name p2_rows --pools '' --rows data/processed/sft/train_rows.parquet --rows data/processed/sft/dev_rows.parquet",
              "scripts/data/write_data_card.py                 # this file",
              "scripts/data/build_mixture.py freeze            # M2.5", "```", ""]
    return "\n".join(lines)


def write_card(out: Path = paths.DATA / "README.md", manifests_dir: Path = paths.MANIFESTS, pools_dir: Path = paths.POOLS) -> Path:
    text = render(manifests_dir, pools_dir)
    tmp = out.with_suffix(".md.tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(out)
    return out
