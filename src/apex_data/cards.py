# --- formatting --------------------------------------------------------------------------------------------------------
def fmt(v: Any) -> str:
    if v is None:
        return "–"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int):
        return f"{v:,}"
    if isinstance(v, float):
        return f"{v:,.4g}" if abs(v) < 1000 else f"{v:,.0f}"
    return str(v).replace("|", "\\|").replace("\n", " ")


def pct(x: Any, digits: int = 1) -> str:
    return "–" if x is None else f"{100 * float(x):.{digits}f} %"


def mtok(n: Any) -> str:
    return "–" if n is None else f"{int(n) / 1e6:.2f}M"


def table(headers: Sequence[str], rows: Iterable[Sequence[Any]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(c if isinstance(c, str) else fmt(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def read(path: Path) -> Any:
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def funnel_table(steps: Sequence[Mapping[str, Any]] | None, name_keys: Sequence[str] = ("filter", "step", "stage", "gate", "rule")) -> str:
    if not steps:
        return "_not recorded_"
    rows = []
    for s in steps:
        name = next((s[k] for k in name_keys if s.get(k) is not None), "?")
        reasons = s.get("reasons")
        rows.append([str(name), s.get("n_in"), s.get("n_dropped"), s.get("n_out"),
                     ", ".join(f"{k} {v}" for k, v in reasons.items()) if isinstance(reasons, dict) and reasons else ""])
    return table(["filter", "n_in", "n_dropped", "n_out", "reasons"], rows)


def hard51_languages(config: Path = paths.CONFIGS / "eval" / "swebench_pro_v2_hard.yaml") -> dict[str, int] | None:
    """The public language profile of the 51 HARD tasks recorded in the evaluation lock (a `languages` mapping)."""
    try:
        doc = yaml.safe_load(config.read_text(encoding="utf-8"))
    except OSError:
        return None

    def find(node: Any) -> Any:
        if isinstance(node, dict):
            if isinstance(node.get("languages"), dict):
                return node["languages"]
            for v in node.values():
                hit = find(v)
                if hit is not None:
                    return hit
        return None

    langs = find(doc)
    return {str(k): int(v) for k, v in langs.items()} if langs else None


